-- Official Police nationale competition calendar, refreshed server-side.
create table if not exists public.official_competition_events (
  id uuid primary key default gen_random_uuid(),
  track text not null check (track in ('gpx', 'pa')),
  session_label text not null,
  region_label text,
  event_type text not null check (event_type in ('registration', 'written', 'sport', 'oral', 'result', 'other')),
  date_text text not null,
  starts_on date,
  ends_on date,
  source_url text not null check (source_url like 'https://www.police-nationale.interieur.gouv.fr/%'),
  source_fingerprint text not null unique,
  is_provisional boolean not null default true,
  is_active boolean not null default true,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.official_calendar_sync_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null check (status in ('running', 'success', 'partial', 'failed')),
  events_found integer not null default 0,
  error_message text,
  source_status jsonb not null default '{}'::jsonb
);

create table if not exists public.official_calendar_sync_config (
  singleton boolean primary key default true check (singleton),
  invocation_token text not null,
  updated_at timestamptz not null default now()
);
insert into public.official_calendar_sync_config (singleton, invocation_token)
values (true, encode(gen_random_bytes(32), 'hex'))
on conflict (singleton) do nothing;

alter table public.official_competition_events enable row level security;
alter table public.official_calendar_sync_runs enable row level security;
alter table public.official_calendar_sync_config enable row level security;

drop policy if exists official_events_authenticated_read on public.official_competition_events;
create policy official_events_authenticated_read
on public.official_competition_events for select to authenticated using (is_active);

revoke all on public.official_competition_events from anon, authenticated;
revoke all on public.official_calendar_sync_runs from anon, authenticated;
revoke all on public.official_calendar_sync_config from anon, authenticated;
grant select on public.official_competition_events to authenticated;

create index if not exists official_events_track_date_idx
  on public.official_competition_events (track, starts_on, event_type)
  where is_active;

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

select cron.schedule(
  'copiq-official-police-calendar-daily',
  '17 4 * * *',
  $job$
  select net.http_post(
    url := 'https://nuoonagnkhbeeymtvrcn.supabase.co/functions/v1/sync_official_police_calendar',
    headers := jsonb_build_object('Content-Type', 'application/json'),
    body := jsonb_build_object(
      'token', (select invocation_token from public.official_calendar_sync_config where singleton)
    ),
    timeout_milliseconds := 20000
  );
  $job$
);

comment on table public.official_competition_events is
  'Read-only app cache of provisional dates published by Police nationale.';
