-- COP'IQ beta: configuration distante du démarrage et preuve d'acceptation CGV.

create table if not exists public.app_runtime_config (
  id smallint primary key default 1 check (id = 1),
  legal_warning_enabled boolean not null default true,
  legal_warning_revision integer not null default 1 check (legal_warning_revision > 0),
  legal_warning_title text not null default 'Avertissement',
  legal_warning_content text not null default E'COP’IQ est une application privée de préparation scolaire.\nElle n’est ni affiliée ni autorisée par le Gouvernement.\nLes contenus sont pédagogiques et ne remplacent pas les instructions officielles.',
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

insert into public.app_runtime_config (id) values (1)
on conflict (id) do nothing;

alter table public.app_runtime_config enable row level security;
revoke all on public.app_runtime_config from public;
grant select on public.app_runtime_config to anon, authenticated;

drop policy if exists app_runtime_config_public_read on public.app_runtime_config;
create policy app_runtime_config_public_read on public.app_runtime_config
for select to anon, authenticated using (id = 1);

alter table public.user_profiles
  add column if not exists cgv_version text,
  add column if not exists cgv_acceptance_source text,
  add column if not exists cgv_recorded_at timestamptz;

create table if not exists public.cgv_consent_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  cgv_version text not null,
  accepted_at_client timestamptz,
  recorded_at timestamptz not null default now(),
  source text not null,
  platform text,
  terms_url text not null default 'https://copiq.fr/cgv/',
  unique (user_id, cgv_version)
);

create index if not exists cgv_consent_events_user_idx
  on public.cgv_consent_events (user_id, recorded_at desc);

alter table public.cgv_consent_events enable row level security;
revoke all on public.cgv_consent_events from public, anon, authenticated;
drop policy if exists cgv_consent_events_no_direct_access on public.cgv_consent_events;
create policy cgv_consent_events_no_direct_access on public.cgv_consent_events
for all to anon, authenticated using (false) with check (false);

-- La preuve est créée côté serveur depuis les métadonnées du signUp.
create or replace function public.handle_new_user_minimal()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_cgv_accepted boolean := coalesce((new.raw_user_meta_data->>'cgv_accepted')::boolean, false);
  v_cgv_version text := nullif(new.raw_user_meta_data->>'cgv_version', '');
  v_client_at timestamptz;
  v_platform text := nullif(new.raw_user_meta_data->>'platform', '');
begin
  begin
    v_client_at := nullif(new.raw_user_meta_data->>'cgv_accepted_client_at', '')::timestamptz;
  exception when others then
    v_client_at := null;
  end;

  insert into public.user_profiles (
    user_id, email, avatar_index, user_mode, role, cgv_accepted,
    cgv_accepted_at, cgv_version, cgv_acceptance_source, cgv_recorded_at,
    created_at, updated_at
  ) values (
    new.id, new.email, 1, 'exam', 'user', v_cgv_accepted,
    case when v_cgv_accepted then coalesce(v_client_at, now()) end,
    case when v_cgv_accepted then coalesce(v_cgv_version, '2026-08') end,
    case when v_cgv_accepted then 'explicit_signup' end,
    case when v_cgv_accepted then now() end,
    now(), now()
  )
  on conflict (user_id) do update set
    email = excluded.email,
    cgv_accepted = public.user_profiles.cgv_accepted or excluded.cgv_accepted,
    cgv_accepted_at = coalesce(public.user_profiles.cgv_accepted_at, excluded.cgv_accepted_at),
    cgv_version = coalesce(public.user_profiles.cgv_version, excluded.cgv_version),
    cgv_acceptance_source = coalesce(public.user_profiles.cgv_acceptance_source, excluded.cgv_acceptance_source),
    cgv_recorded_at = coalesce(public.user_profiles.cgv_recorded_at, excluded.cgv_recorded_at),
    updated_at = now();

  if v_cgv_accepted then
    insert into public.cgv_consent_events (
      user_id, cgv_version, accepted_at_client, source, platform
    ) values (
      new.id, coalesce(v_cgv_version, '2026-08'), v_client_at,
      'explicit_signup', v_platform
    ) on conflict (user_id, cgv_version) do nothing;
  end if;
  return new;
end;
$$;

revoke all on function public.handle_new_user_minimal() from public, anon, authenticated;

-- Les anciens comptes ont obligatoirement traversé l'écran d'acceptation,
-- mais l'heure du clic n'a pas été conservée. La date de création est donc
-- explicitement marquée comme reconstituée, jamais comme preuve exacte du clic.
update public.user_profiles
set cgv_accepted = true,
    cgv_accepted_at = coalesce(cgv_accepted_at, created_at),
    cgv_version = coalesce(cgv_version, 'legacy-pre-2026-08'),
    cgv_acceptance_source = coalesce(cgv_acceptance_source, 'legacy_signup_inferred'),
    cgv_recorded_at = coalesce(cgv_recorded_at, now())
where not cgv_accepted;

insert into public.cgv_consent_events (
  user_id, cgv_version, accepted_at_client, recorded_at, source, platform
)
select user_id, coalesce(cgv_version, 'legacy-pre-2026-08'), cgv_accepted_at,
       coalesce(cgv_recorded_at, now()), 'legacy_signup_inferred', null
from public.user_profiles
where cgv_acceptance_source = 'legacy_signup_inferred'
on conflict (user_id, cgv_version) do nothing;

create or replace function public.app_runtime_config_admin_get()
returns public.app_runtime_config
language plpgsql security definer set search_path = public, auth as $$
begin
  perform public.information_admin_guard();
  return (select c from public.app_runtime_config c where c.id = 1);
end;
$$;

create or replace function public.app_runtime_config_admin_update(
  p_enabled boolean,
  p_title text,
  p_content text,
  p_redisplay_to_all boolean default false
)
returns public.app_runtime_config
language plpgsql security definer set search_path = public, auth as $$
begin
  perform public.information_admin_guard();
  update public.app_runtime_config
  set legal_warning_enabled = p_enabled,
      legal_warning_title = coalesce(nullif(trim(p_title), ''), legal_warning_title),
      legal_warning_content = coalesce(nullif(trim(p_content), ''), legal_warning_content),
      legal_warning_revision = legal_warning_revision + case when p_redisplay_to_all then 1 else 0 end,
      updated_at = now(),
      updated_by = auth.uid()
  where id = 1;
  return (select c from public.app_runtime_config c where c.id = 1);
end;
$$;

create or replace function public.community_admin_user_cgv_status(p_user_id uuid)
returns jsonb
language plpgsql security definer set search_path = public, auth as $$
begin
  perform public.community_admin_guard();
  return coalesce((
    select jsonb_build_object(
      'accepted', u.cgv_accepted,
      'accepted_at', u.cgv_accepted_at,
      'version', u.cgv_version,
      'source', u.cgv_acceptance_source,
      'recorded_at', u.cgv_recorded_at,
      'historical_inference', u.cgv_acceptance_source = 'legacy_signup_inferred'
    ) from public.user_profiles u where u.user_id = p_user_id
  ), '{}'::jsonb);
end;
$$;

revoke all on function public.app_runtime_config_admin_get() from public, anon;
revoke all on function public.app_runtime_config_admin_update(boolean,text,text,boolean) from public, anon;
revoke all on function public.community_admin_user_cgv_status(uuid) from public, anon;
grant execute on function public.app_runtime_config_admin_get() to authenticated;
grant execute on function public.app_runtime_config_admin_update(boolean,text,text,boolean) to authenticated;
grant execute on function public.community_admin_user_cgv_status(uuid) to authenticated;
