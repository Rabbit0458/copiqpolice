create or replace function private.capture_course_version()
returns trigger language plpgsql security definer
set search_path = pg_catalog, public, private
as $$
begin
  if row(new.*) is distinct from row(old.*) then
    insert into public.cours_scolarite_versions
      (course_id, revision, snapshot, change_reason, actor_auth_uid)
    values
      (old.id, old.revision, to_jsonb(old), 'Sauvegarde automatique avant modification', auth.uid())
    on conflict (course_id, revision) do nothing;
    new.revision := old.revision + 1;
    new.updated_at := now();
  end if;
  return new;
end;
$$;
revoke all on function private.capture_course_version() from public, anon, authenticated;

drop trigger if exists cours_scolarite_capture_version on public.cours_scolarite;
create trigger cours_scolarite_capture_version
before update on public.cours_scolarite
for each row execute function private.capture_course_version();

