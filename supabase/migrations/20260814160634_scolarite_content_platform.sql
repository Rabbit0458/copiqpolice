create or replace function public.cours_admin_upsert(p_data jsonb)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public
as $$
declare v_id bigint; v_old jsonb; v_route text := nullif(trim(p_data->>'route'), '');
begin
  perform public.quiz_admin_guard();
  if v_route is null or nullif(trim(p_data->>'title'), '') is null or nullif(trim(p_data->>'module'), '') is null then
    raise exception 'Route, titre et module sont obligatoires.' using errcode = '22023';
  end if;
  select id, to_jsonb(c) into v_id, v_old from public.cours_scolarite c where c.route = v_route for update;
  if v_id is null then
    insert into public.cours_scolarite
      (route, track, module, section, code, title, subtitle, body_md, content_blocks,
       key_points, legal_refs, quiz_module, color_hex, sort_order, is_published,
       publication_status, scheduled_at, source_path, source_hash, source_kind,
       parent_route, metadata)
    values
      (v_route, coalesce(nullif(p_data->>'track',''),'gpx'), p_data->>'module', p_data->>'section',
       p_data->>'code', p_data->>'title', p_data->>'subtitle', coalesce(p_data->>'body_md',''),
       coalesce(p_data->'content_blocks','[]'::jsonb), coalesce(p_data->'key_points','[]'::jsonb),
       coalesce(p_data->'legal_refs','[]'::jsonb), p_data->>'quiz_module',
       coalesce(nullif(p_data->>'color_hex',''),'#1147D9'), coalesce((p_data->>'sort_order')::int,100),
       coalesce((p_data->>'publication_status') = 'published', false),
       coalesce(nullif(p_data->>'publication_status',''),'draft'), (p_data->>'scheduled_at')::timestamptz,
       p_data->>'source_path', p_data->>'source_hash', coalesce(nullif(p_data->>'source_kind',''),'course'),
       p_data->>'parent_route', coalesce(p_data->'metadata','{}'::jsonb))
    returning id into v_id;
  else
    update public.cours_scolarite set
      track=coalesce(p_data->>'track',track), module=coalesce(p_data->>'module',module),
      section=case when p_data ? 'section' then p_data->>'section' else section end,
      code=case when p_data ? 'code' then p_data->>'code' else code end,
      title=coalesce(p_data->>'title',title), subtitle=case when p_data ? 'subtitle' then p_data->>'subtitle' else subtitle end,
      body_md=coalesce(p_data->>'body_md',body_md), content_blocks=coalesce(p_data->'content_blocks',content_blocks),
      key_points=coalesce(p_data->'key_points',key_points), legal_refs=coalesce(p_data->'legal_refs',legal_refs),
      quiz_module=case when p_data ? 'quiz_module' then p_data->>'quiz_module' else quiz_module end,
      color_hex=coalesce(p_data->>'color_hex',color_hex), sort_order=coalesce((p_data->>'sort_order')::int,sort_order),
      source_path=coalesce(p_data->>'source_path',source_path), source_hash=coalesce(p_data->>'source_hash',source_hash),
      source_kind=coalesce(p_data->>'source_kind',source_kind), parent_route=case when p_data ? 'parent_route' then p_data->>'parent_route' else parent_route end,
      metadata=coalesce(p_data->'metadata',metadata)
    where id=v_id;
  end if;
  insert into public.admin_audit_logs
    (actor_auth_uid, action, severity, success, target_table, target_id, old_value, new_value, comment)
  values (auth.uid(), case when v_old is null then 'cours_scolarite.create' else 'cours_scolarite.update' end,
    'info', true, 'cours_scolarite', v_id::text, v_old - 'body_md' - 'content_blocks',
    p_data - 'body_md' - 'content_blocks', 'Panel admin — fiche de cours');
  return jsonb_build_object('ok',true,'id',v_id,'route',v_route);
end;
$$;
revoke all on function public.cours_admin_upsert(jsonb) from public, anon;
grant execute on function public.cours_admin_upsert(jsonb) to authenticated, service_role;

create or replace function public.cours_admin_versions(p_route text)
returns table(id bigint, revision integer, change_reason text, actor_auth_uid uuid, created_at timestamptz)
language plpgsql security definer set search_path = pg_catalog, public
as $$
begin
  perform public.quiz_admin_guard();
  return query select v.id, v.revision, v.change_reason, v.actor_auth_uid, v.created_at
  from public.cours_scolarite_versions v join public.cours_scolarite c on c.id=v.course_id
  where c.route=p_route order by v.revision desc;
end;
$$;
revoke all on function public.cours_admin_versions(text) from public, anon;
grant execute on function public.cours_admin_versions(text) to authenticated, service_role;

create or replace function public.cours_scolarite_catalog(p_track text default null)
returns setof public.cours_scolarite language sql stable security invoker
set search_path = pg_catalog, public
as $$
  select c.* from public.cours_scolarite c
  where c.is_published and c.publication_status='published'
    and (p_track is null or c.track=p_track)
  order by c.track,c.module,c.section,c.sort_order,c.id;
$$;
revoke all on function public.cours_scolarite_catalog(text) from public, anon;
grant execute on function public.cours_scolarite_catalog(text) to authenticated, service_role;

