begin;

create table if not exists public.active_verification_questions (
  id bigint generated by default as identity primary key,
  version integer not null check (version > 0),
  position smallint not null check (position between 1 and 4),
  prompt text not null check (length(trim(prompt)) > 0),
  expected_answer text not null check (length(trim(expected_answer)) > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (version, position)
);

create table if not exists public.active_access_verifications (
  user_id uuid primary key references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','granted','revoked')),
  verification_version integer,
  granted_at timestamptz,
  revoked_at timestamptz,
  granted_by uuid,
  revoked_by uuid,
  revoke_reason text,
  last_attempt_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.active_verification_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  verification_version integer not null,
  score smallint not null check (score between 0 and 4),
  passed boolean not null,
  started_at timestamptz not null default now(),
  completed_at timestamptz not null default now(),
  cooldown_until timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.active_verification_answers (
  id bigint generated by default as identity primary key,
  attempt_id uuid not null references public.active_verification_attempts(id) on delete cascade,
  question_id bigint not null references public.active_verification_questions(id) on delete restrict,
  position smallint not null check (position between 1 and 4),
  prompt_snapshot text not null,
  submitted_answer text not null,
  normalized_answer text not null,
  correct boolean not null,
  created_at timestamptz not null default now(),
  unique (attempt_id, question_id)
);

create index if not exists active_attempts_user_created_idx
  on public.active_verification_attempts (user_id, completed_at desc);
create index if not exists active_access_status_idx
  on public.active_access_verifications (status, updated_at desc);

