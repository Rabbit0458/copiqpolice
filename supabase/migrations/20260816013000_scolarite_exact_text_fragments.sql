-- Textes exacts des pages Flutter existantes.
-- Le design reste dans les widgets Dart ; seule la valeur de chaque fragment
-- éditorial est distante et librement modifiable.

create table if not exists public.scolarite_content_fragments (
  source_path text not null references public.scolarite_source_registry(source_path)
    on update cascade on delete restrict,
  fragment_key text not null,
  panel text not null default 'Informations générales',
  position integer not null check (position > 0),
  component text not null default 'string',
  text_value text not null,
  original_text text not null,
  style_payload jsonb not null default '{}'::jsonb,
  is_editable boolean not null default true,
  revision integer not null default 1,
  updated_at timestamptz not null default now(),
  updated_by uuid,
  primary key (source_path, fragment_key)
);

create index if not exists scolarite_content_fragments_panel_idx
  on public.scolarite_content_fragments(source_path, panel, position);

create table if not exists public.scolarite_content_links (
  id bigint generated by default as identity primary key,
  gpx_source_path text not null unique references public.scolarite_source_registry(source_path)
    on update cascade on delete restrict,
  pa_source_path text not null unique references public.scolarite_source_registry(source_path)
    on update cascade on delete restrict,
  link_status text not null default 'linked' check (link_status in ('linked', 'separated')),
  confirmed_at timestamptz,
  confirmed_by uuid,
  separated_at timestamptz,
  separated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (gpx_source_path <> pa_source_path)
);

alter table public.scolarite_content_fragments enable row level security;
alter table public.scolarite_content_links enable row level security;

drop policy if exists scolarite_fragments_authenticated_read on public.scolarite_content_fragments;
create policy scolarite_fragments_authenticated_read
  on public.scolarite_content_fragments for select to authenticated using (true);
drop policy if exists scolarite_fragments_admin_write on public.scolarite_content_fragments;
create policy scolarite_fragments_admin_write
  on public.scolarite_content_fragments for all to authenticated
  using (public.has_admin_permission('quiz.write'))
  with check (public.has_admin_permission('quiz.write'));

drop policy if exists scolarite_links_admin on public.scolarite_content_links;
create policy scolarite_links_admin
  on public.scolarite_content_links for all to authenticated
  using (public.has_admin_permission('quiz.write'))
  with check (public.has_admin_permission('quiz.write'));

revoke all on public.scolarite_content_fragments from public, anon;
revoke all on public.scolarite_content_links from public, anon;
grant select on public.scolarite_content_fragments to authenticated, service_role;
grant select, insert, update on public.scolarite_content_links to authenticated, service_role;
grant insert, update on public.scolarite_content_fragments to authenticated, service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;

create or replace function public.scolarite_admin_get_editor(p_source_path text)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public
as $$
declare v_link jsonb; v_linked_source text; v_track text; v_fragments jsonb;
begin
  perform public.quiz_admin_guard();
  select track into v_track from public.scolarite_source_registry where source_path=p_source_path;
  if v_track is null then raise exception 'Source introuvable.' using errcode='22023'; end if;

  select to_jsonb(l),
    case when l.gpx_source_path=p_source_path then l.pa_source_path else l.gpx_source_path end
  into v_link, v_linked_source
  from public.scolarite_content_links l
  where l.gpx_source_path=p_source_path or l.pa_source_path=p_source_path;

  select coalesce(jsonb_agg(to_jsonb(f) order by f.position), '[]'::jsonb)
  into v_fragments from public.scolarite_content_fragments f
  where f.source_path=p_source_path;

  return jsonb_build_object(
    'source_path', p_source_path,
    'track', v_track,
    'fragments', v_fragments,
    'link', v_link,
    'linked_source_path', v_linked_source
  );
end;
$$;
revoke all on function public.scolarite_admin_get_editor(text) from public, anon;
grant execute on function public.scolarite_admin_get_editor(text) to authenticated, service_role;

create or replace function public.scolarite_admin_update_fragment(
  p_source_path text,
  p_fragment_key text,
  p_text_value text,
  p_apply_linked boolean default false
)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public
as $$
declare v_link public.scolarite_content_links%rowtype; v_other text; v_count integer;
begin
  perform public.quiz_admin_guard();
  if p_text_value is null then raise exception 'Le texte ne peut pas être nul.' using errcode='22023'; end if;

  select * into v_link from public.scolarite_content_links
  where link_status='linked' and (gpx_source_path=p_source_path or pa_source_path=p_source_path)
  for update;
  if v_link.id is not null and not p_apply_linked then
    raise exception 'Ce cours est lié à sa version GPX/PA : la confirmation du double aperçu est obligatoire.'
      using errcode='22023';
  end if;

  update public.scolarite_content_fragments set
    text_value=p_text_value, revision=revision+1, updated_at=now(), updated_by=auth.uid()
  where source_path=p_source_path and fragment_key=p_fragment_key and is_editable;
  get diagnostics v_count = row_count;
  if v_count <> 1 then raise exception 'Fragment introuvable ou non modifiable.' using errcode='22023'; end if;

  if v_link.id is not null then
    v_other := case when v_link.gpx_source_path=p_source_path then v_link.pa_source_path else v_link.gpx_source_path end;
    update public.scolarite_content_fragments set
      text_value=p_text_value, revision=revision+1, updated_at=now(), updated_by=auth.uid()
    where source_path=v_other and fragment_key=p_fragment_key and is_editable;
  end if;

  insert into public.admin_audit_logs
    (actor_auth_uid, action, severity, success, target_table, target_id, new_value, comment)
  values (auth.uid(), 'scolarite.fragment.update', 'info', true,
    'scolarite_content_fragments', p_source_path || ':' || p_fragment_key,
    jsonb_build_object('text_value',p_text_value,'apply_linked',p_apply_linked),
    'Modification du texte sans changement de design');
  return jsonb_build_object('ok',true,'linked_updated',v_link.id is not null);
end;
$$;
revoke all on function public.scolarite_admin_update_fragment(text,text,text,boolean) from public, anon;
grant execute on function public.scolarite_admin_update_fragment(text,text,text,boolean) to authenticated, service_role;

create or replace function public.scolarite_admin_separate_link(p_source_path text)
returns jsonb language plpgsql security definer
set search_path = pg_catalog, public
as $$
declare v_id bigint;
begin
  perform public.quiz_admin_guard();
  update public.scolarite_content_links set
    link_status='separated', separated_at=now(), separated_by=auth.uid(), updated_at=now()
  where link_status='linked' and (gpx_source_path=p_source_path or pa_source_path=p_source_path)
  returning id into v_id;
  if v_id is null then raise exception 'Aucune liaison active.' using errcode='22023'; end if;
  return jsonb_build_object('ok',true,'link_id',v_id);
end;
$$;
revoke all on function public.scolarite_admin_separate_link(text) from public, anon;
grant execute on function public.scolarite_admin_separate_link(text) to authenticated, service_role;

