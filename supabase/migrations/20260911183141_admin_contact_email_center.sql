-- COP'IQ — Centre de contact utilisateurs.
-- Les adresses restent côté serveur. Seul le propriétaire authentifié en AAL2
-- peut préparer, tester et lancer une communication de service.

begin;

create table if not exists public.admin_email_campaigns (
  id uuid primary key default gen_random_uuid(),
  campaign_type text not null check (campaign_type in ('product_update', 'service_information', 'individual_message')),
  audience_kind text not null check (audience_kind in ('all', 'individual')),
  target_user_id uuid references auth.users(id) on delete set null,
  subject text not null check (char_length(btrim(subject)) between 3 and 160),
  headline text not null check (char_length(btrim(headline)) between 3 and 180),
  body_text text not null check (char_length(btrim(body_text)) between 10 and 8000),
  cta_label text check (cta_label is null or char_length(btrim(cta_label)) between 2 and 48),
  cta_url text check (cta_url is null or cta_url ~* '^https://'),
  status text not null default 'draft' check (status in ('draft', 'sending', 'sent', 'partial', 'failed', 'cancelled')),
  recipient_count integer not null default 0 check (recipient_count >= 0),
  submitted_count integer not null default 0 check (submitted_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_by_email text not null,
  last_error text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz
);

create table if not exists public.admin_email_deliveries (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.admin_email_campaigns(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  recipient_email text not null,
  recipient_name text,
  status text not null default 'pending' check (status in ('pending', 'submitted', 'failed', 'skipped')),
  provider_id text,
  error text,
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  unique (campaign_id, user_id),
  unique (campaign_id, recipient_email)
);

create table if not exists public.admin_email_batches (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.admin_email_campaigns(id) on delete cascade,
  batch_number integer not null check (batch_number >= 0),
  status text not null default 'pending' check (status in ('pending', 'submitted', 'failed')),
  recipient_count integer not null check (recipient_count between 1 and 500),
  provider_ids jsonb not null default '[]'::jsonb,
  error text,
  created_at timestamptz not null default now(),
  submitted_at timestamptz,
  unique (campaign_id, batch_number)
);

create index if not exists admin_email_campaigns_created_idx
  on public.admin_email_campaigns (created_at desc);
create index if not exists admin_email_deliveries_campaign_status_idx
  on public.admin_email_deliveries (campaign_id, status, id);

alter table public.admin_email_campaigns enable row level security;
alter table public.admin_email_campaigns force row level security;
alter table public.admin_email_deliveries enable row level security;
alter table public.admin_email_deliveries force row level security;
alter table public.admin_email_batches enable row level security;
alter table public.admin_email_batches force row level security;

revoke all on table public.admin_email_campaigns from public, anon, authenticated;
revoke all on table public.admin_email_deliveries from public, anon, authenticated;
revoke all on table public.admin_email_batches from public, anon, authenticated;
grant all on table public.admin_email_campaigns to service_role;
grant all on table public.admin_email_deliveries to service_role;
grant all on table public.admin_email_batches to service_role;
grant usage, select on sequence public.admin_email_deliveries_id_seq to service_role;

create or replace function public.admin_contact_owner_context()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin public.admin_users;
begin
  select * into v_admin
  from public.admin_users a
  where a.auth_uid = auth.uid()
    and not a.disabled
    and (a.locked_until is null or a.locked_until <= now())
    and (a.expires_at is null or a.expires_at > now())
  limit 1;

  if v_admin.id is null or lower(v_admin.role) <> 'owner' then
    raise exception 'Accès refusé : seul le propriétaire peut contacter les utilisateurs.' using errcode = '42501';
  end if;
  if not public.admin_require_aal2() then
    raise exception 'Accès refusé : double authentification requise.' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'admin_id', v_admin.id,
    'auth_uid', auth.uid(),
    'email', v_admin.email,
    'role', v_admin.role
  );
end;
$$;

revoke all on function public.admin_contact_owner_context() from public, anon;
grant execute on function public.admin_contact_owner_context() to authenticated;

comment on table public.admin_email_campaigns is
  'Brouillons et historique des communications de service envoyées depuis le panel owner.';
comment on table public.admin_email_deliveries is
  'Instantané privé des destinataires et résultat de remise au prestataire ; jamais exposé au client.';
comment on table public.admin_email_batches is
  'Lots Brevo idempotents : l''identifiant UUID du lot sert de clé anti-double envoi.';
comment on function public.admin_contact_owner_context() is
  'Garde owner + AAL2 appelée par la fonction Edge du centre de contact.';

commit;
